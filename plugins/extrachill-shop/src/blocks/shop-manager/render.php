<?php
/**
 * Shop Manager block - server-side render.
 *
 * Resolves the sellers the current user can manage and the selected seller,
 * then hands them to the React app. Every API call the app makes re-checks
 * authority for the seller it names.
 *
 * @package ExtraChillShop
 */

defined( 'ABSPATH' ) || exit;

if ( ! is_user_logged_in() ) {
	echo '<div class="notice notice-info"><p>';
	printf(
		/* translators: %s: login URL. */
		wp_kses_post( __( 'Please <a href="%s">log in</a> to manage your shop.', 'extrachill-shop' ) ),
		esc_url( wp_login_url( (string) get_permalink() ) )
	);
	echo '</p></div>';
	return;
}

// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only seller preselection; authority is checked server-side.
$ec_shop_requested = isset( $_GET['seller'] ) && is_string( $_GET['seller'] ) ? sanitize_text_field( wp_unslash( $_GET['seller'] ) ) : null;
$ec_shop_ref       = null === $ec_shop_requested ? null : extrachill_shop_parse_seller_key( $ec_shop_requested );

// Page gate: the user manages some seller (Users discovery), or the seller
// they asked for passes the seller permission primitive (e.g. an admin).
$ec_shop_allowed = ( function_exists( 'ec_can_manage_shop' ) && ec_can_manage_shop() )
	|| ( $ec_shop_ref && true === extrachill_shop_can_manage_seller( get_current_user_id(), $ec_shop_ref ) );
if ( ! $ec_shop_allowed ) {
	echo '<div class="notice notice-info"><p>' . esc_html__( 'Shop management is not available for your account.', 'extrachill-shop' ) . '</p></div>';
	return;
}

$ec_shop_state = extrachill_shop_get_manager_state( $ec_shop_requested );

if ( null === $ec_shop_state['selected'] ) {
	$ec_shop_message = null === $ec_shop_requested
		? __( 'You do not manage any artist, venue or promoter shops yet.', 'extrachill-shop' )
		: __( 'This shop is not available to you.', 'extrachill-shop' );
	echo '<div class="notice notice-error"><p>' . esc_html( $ec_shop_message ) . '</p></div>';
	return;
}

$ec_shop_config = array(
	'sellers'  => $ec_shop_state['sellers'],
	'selected' => $ec_shop_state['selected'],
	'restUrl'  => esc_url_raw( rest_url() ),
	'nonce'    => wp_create_nonce( 'wp_rest' ),
	'pageUrl'  => esc_url_raw( (string) get_permalink() ),
);

$ec_shop_wrapper = get_block_wrapper_attributes( array( 'class' => 'ec-shop-manager' ) );

printf(
	'<div %1$s><div id="ec-shop-manager-root" data-config="%2$s"></div></div>',
	$ec_shop_wrapper, // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by get_block_wrapper_attributes().
	esc_attr( (string) wp_json_encode( $ec_shop_config ) )
);
