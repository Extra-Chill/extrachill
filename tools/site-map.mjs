#!/usr/bin/env node
// Renders MONOREPO.md's "where each component runs" table from the network
// rig's activation matrix (rigs/extrachill-network/components.json), so the
// doc and the rig that boots the network can't disagree.
//
//   node tools/site-map.mjs          rewrite the table in MONOREPO.md
//   node tools/site-map.mjs --check  exit 1 if the table is out of date
//
// It also fails when a directory under plugins/ has no rig entry: every
// monorepo plugin has to be booted by the rig, so the map always covers it.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docPath = path.join(root, 'MONOREPO.md');
const BEGIN = '<!-- site-map:begin (generated by tools/site-map.mjs; edit rigs/extrachill-network/components.json) -->';
const END = '<!-- site-map:end -->';

const rig = JSON.parse(readFileSync(path.join(root, 'rigs/extrachill-network/components.json'), 'utf8'));
const rigPlugins = new Map(rig.plugins.map((plugin) => [plugin.slug, plugin]));

const dirs = (relative) => readdirSync(path.join(root, relative), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

function scopeLabel(scope) {
  if (scope === 'network') return 'all sites (network-activated)';
  return [...scope].sort().join(', ');
}

// One label per activation; name each extra plugin file next to its scope.
function activeOn(plugin) {
  const activations = plugin.activations ?? [];
  const mainFile = `${plugin.slug}/${plugin.slug}.php`;
  return activations
    .map((activation) => {
      const label = scopeLabel(activation.scope);
      if (activations.length === 1 || activation.pluginFile === mainFile) return label;
      return `${label}: \`${path.basename(activation.pluginFile, '.php')}\``;
    })
    .join('; ');
}

function renderSiteMap() {
  const missing = [];
  const rows = [];
  for (const slug of dirs('plugins')) {
    const plugin = rigPlugins.get(slug);
    if (!plugin) {
      missing.push(slug);
      continue;
    }
    rows.push([`\`${slug}\``, `\`plugins/${slug}\``, activeOn(plugin)]);
  }
  for (const slug of dirs('themes')) {
    const label = slug === rig.theme?.slug ? 'all sites (network theme)' : 'not booted by the rig';
    rows.push([`\`${slug}\``, `\`themes/${slug}\``, label]);
  }
  for (const dir of dirs('packages')) {
    const manifest = path.join(root, 'packages', dir, 'package.json');
    const name = existsSync(manifest) ? JSON.parse(readFileSync(manifest, 'utf8')).name : dir;
    rows.push([`\`${name}\``, `\`packages/${dir}\``, 'npm package (build-time)']);
  }
  if (missing.length) {
    throw new Error(`plugins/ without an entry in rigs/extrachill-network/components.json: ${missing.join(', ')}`);
  }
  const lines = ['| Component | Path | Active on |', '|---|---|---|', ...rows.map((row) => `| ${row.join(' | ')} |`)];
  return `${BEGIN}\n${lines.join('\n')}\n${END}`;
}

function main() {
  const doc = readFileSync(docPath, 'utf8');
  const start = doc.indexOf(BEGIN);
  const stop = doc.indexOf(END);
  if (start === -1 || stop === -1 || stop < start) throw new Error(`MONOREPO.md is missing the ${BEGIN} … ${END} markers.`);
  const next = doc.slice(0, start) + renderSiteMap() + doc.slice(stop + END.length);
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error('MONOREPO.md site map is out of date. Run: node tools/site-map.mjs');
      process.exit(1);
    }
    console.log('MONOREPO.md site map is up to date.');
    return;
  }
  writeFileSync(docPath, next);
  console.log('MONOREPO.md site map written.');
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
