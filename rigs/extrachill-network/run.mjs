async function loadJourney(id, topology) {
  const dir = path.join(packageRoot, 'journeys', id);
  const journeyPath = path.join(dir, 'journey.json');
  let journey;
  try {
    journey = JSON.parse(await readFile(journeyPath, 'utf8'));
  } catch (error) {
    throw new Error(`Journey '${id}' has an unreadable journey.json: ${error.message}`);
  }
  const personaExists = async (file) => {
    try {
      await readFile(path.join(packageRoot, 'personas', file), 'utf8');
      return true;
    } catch {
      return false;
    }
  };
  const codeFileExists = async (file) => {
    try {
      await readFile(path.join(dir, file), 'utf8');
      return true;
    } catch {
      return false;
    }
  };
  await validateJourneyDocument(journey, id, topology, personaExists, codeFileExists);
  return { journey, dir };
}

/**
 * Validate a journey document against the journey contract
 * (extrachill-network/journey/v1). `personaExists` and `codeFileExists` are
 * async predicates so the rules are testable without fixture files.
 */
export async function validateJourneyDocument(journey, id, topology, personaExists = async () => true, codeFileExists = async () => true) {
  if (journey.schema !== 'extrachill-network/journey/v1') {
    throw new Error(`Journey '${id}' must declare schema "extrachill-network/journey/v1", got ${JSON.stringify(journey.schema)}.`);
  }
  if (journey.id !== id) {
    throw new Error(`Journey '${id}' journey.json declares id ${JSON.stringify(journey.id)}; the id must match the directory name.`);
  }
  if (!Array.isArray(journey.sites) || journey.sites.length === 0) {
    throw new Error(`Journey '${id}' must declare a non-empty "sites" array of topology domains.`);
  }
  for (const domain of journey.sites) {
    if (!topology.sites.some((site) => site.domain === domain)) {
      throw new Error(`Journey '${id}' references site '${domain}', which is not a domain in network-topology.json. Sites are resolved by domain, never by blog ID.`);
    }
  }
  if (journey.persona?.file && !(await personaExists(journey.persona.file))) {
    throw new Error(`Journey '${id}' pins persona file '${journey.persona.file}', which is missing from rigs/extrachill-network/personas/.`);
  }
  for (const phase of ['seed', 'grade']) {
    if (journey[phase]?.codeFile && !(await codeFileExists(journey[phase].codeFile))) {
      throw new Error(`Journey '${id}' ${phase}.codeFile '${journey[phase].codeFile}' does not exist in journeys/${id}/.`);
    }
  }
  if (journey.demo !== undefined) {
    const demo = journey.demo;
    if (!isRecord(demo) || !isRecord(demo.video) || !/^\d+x\d+$/.test(demo.video.viewport ?? '')) {
      throw new Error(`Journey '${id}' demo.video.viewport must be WxH.`);
    }
    if (demo.video.size !== undefined && !/^\d+x\d+$/.test(demo.video.size)) throw new Error(`Journey '${id}' demo.video.size must be WxH.`);
    if (demo.video.maxSeconds !== undefined && (!Number.isInteger(demo.video.maxSeconds) || demo.video.maxSeconds <= 0)) throw new Error(`Journey '${id}' demo.video.maxSeconds must be a positive integer.`);
    if (demo.video.loadKeepMs !== undefined && (!Number.isInteger(demo.video.loadKeepMs) || demo.video.loadKeepMs < 0)) throw new Error(`Journey '${id}' demo.video.loadKeepMs must be a non-negative integer.`);
    if (demo.video.output !== undefined && (!isRecord(demo.video.output) || !['width', 'height', 'fps'].every((key) => Number.isInteger(demo.video.output[key]) && demo.video.output[key] > 0))) throw new Error(`Journey '${id}' demo.video.output requires positive integer width, height, and fps.`);
    if (typeof demo.theme !== 'string' || !/^[a-z0-9-]+\.json$/.test(demo.theme)) throw new Error(`Journey '${id}' demo.theme must name a JSON theme file.`);
    try { await readFile(path.join(packageRoot, 'demo-themes', demo.theme), 'utf8'); } catch { throw new Error(`Journey '${id}' references unknown demo theme '${demo.theme}'.`); }
    if (demo.steps !== undefined) {
      const markers = new Set(journey.steps.map((step) => step.marker).filter(Boolean));
      if (!Array.isArray(demo.steps) || demo.steps.some((step) => !markers.has(step.after ?? step.marker))) throw new Error(`Journey '${id}' demo.steps references unknown markers.`);
    }
    if (!isRecord(demo.presentation)) throw new Error(`Journey '${id}' demo.presentation must be an object.`);
    if (demo.environment !== undefined && (!isRecord(demo.environment) || (demo.environment.colorScheme !== undefined && !['light', 'dark', 'no-preference'].includes(demo.environment.colorScheme)))) throw new Error(`Journey '${id}' demo.environment must be an object with colorScheme light, dark, or no-preference.`);
    if (demo.pacing !== undefined && (!isRecord(demo.pacing) || ['settleMs', 'minCaptionMs'].some((key) => demo.pacing[key] !== undefined && (!Number.isInteger(demo.pacing[key]) || demo.pacing[key] < 0)))) throw new Error(`Journey '${id}' demo.pacing requires non-negative integer settleMs and minCaptionMs values.`);
    if (demo.cover !== undefined && (!isRecord(demo.cover) || typeof demo.cover.marker !== 'string' || !journeyMarkers(journey).includes(demo.cover.marker))) throw new Error(`Journey '${id}' demo.cover.marker must reference an existing step marker.`);
  }
  if (journey.fixtureMuPlugins !== undefined) {
    if (!Array.isArray(journey.fixtureMuPlugins) || journey.fixtureMuPlugins.length === 0 || journey.fixtureMuPlugins.some((file) => typeof file !== 'string' || file.trim() === '')) {
      throw new Error(`Journey '${id}' fixtureMuPlugins must be a non-empty array of non-empty file names relative to journeys/${id}/.`);
    }
    for (const file of journey.fixtureMuPlugins) {
      if (!(await codeFileExists(file))) {
        throw new Error(`Journey '${id}' fixtureMuPlugins entry '${file}' does not exist in journeys/${id}/.`);
      }
    }
  }
  assertJourneyStepScoping(id, journey);
}

