// Resolves the recipe-run --timeout: env override, then the
// extrachill_recipe_timeout setting, then the default. Values use WP Codebox's
// duration format (`<int>ms|s|m`, unitless = ms); a bare integer setting is
// passed through as milliseconds.
export function recipeRunTimeout(settings = {}, env = process.env) {
  const envValue = env.HOMEBOY_WP_CODEBOX_RECIPE_TIMEOUT;
  if (envValue !== undefined && envValue !== '') {
    return normalizeRecipeTimeout(envValue, 'HOMEBOY_WP_CODEBOX_RECIPE_TIMEOUT');
  }
  if (settings.extrachill_recipe_timeout !== undefined) {
    return normalizeRecipeTimeout(settings.extrachill_recipe_timeout, 'extrachill_recipe_timeout');
  }
  return DEFAULT_RECIPE_RUN_TIMEOUT;
}

function normalizeRecipeTimeout(value, label) {
  const raw = typeof value === 'number' ? String(value) : typeof value === 'string' ? value.trim() : '';
  const match = raw.match(/^(\d+)(ms|s|m)?$/);
  if (!match || Number.parseInt(match[1], 10) <= 0) {
    throw new Error(`${label} must be a positive duration such as 3000000ms, 3000s, or 50m.`);
  }
  return raw;
}

export function recipeRunArgs(recipePath, artifactsDirectory, settings = {}, { dryRun = false, env = process.env } = {}) {
  const args = ['recipe-run', '--recipe', recipePath, '--artifacts', artifactsDirectory, '--timeout', recipeRunTimeout(settings, env), '--json'];
  if (dryRun) {
    args.push('--dry-run');
  }
  return args;
}

function assertDemoCodeboxVersion() {
  const executable = process.env.HOMEBOY_WP_CODEBOX_BIN || process.env.WP_CODEBOX_BIN || 'wp-codebox';
  const result = spawnSync(executable, ['--version'], { encoding: 'utf8' });
  const version = `${result.stdout ?? ''} ${result.stderr ?? ''}`.match(/\b(\d+)\.(\d+)\.(\d+)\b/)?.[0];
  if (!version || compareVersions(version, DEMO_MIN_WP_CODEBOX_VERSION) < 0) {
    throw new Error(`Demo mode requires WP Codebox >= ${DEMO_MIN_WP_CODEBOX_VERSION}; found ${version ?? 'unknown'}.`);
  }
}

function compareVersions(a, b) {
  const left = a.split('.').map(Number); const right = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) if (left[i] !== right[i]) return left[i] - right[i];
  return 0;
}

async function renderJourneyDemos(recipe, journeys) {
  const ffmpeg = spawnSync('ffmpeg', ['-version'], { encoding: 'utf8' });
  if (ffmpeg.error || ffmpeg.status !== 0) throw new Error('Demo rendering requires ffmpeg on PATH. Install ffmpeg (https://ffmpeg.org/download.html) and retry.');
  const files = await listFiles(recipe.artifacts.directory);
  const summaries = [];
  for (const file of files.filter((candidate) => candidate.endsWith(path.join('files', 'browser', 'action-summary.json')))) {
    try {
      const summary = JSON.parse(await readFile(file, 'utf8'));
      if (summary.video?.path) summaries.push({ dir: path.dirname(path.dirname(path.dirname(file))), summary });
    } catch { /* not a browser-actions summary */ }
  }
  for (const journey of journeys) {
    const markers = new Set(journeyMarkers(journey));
    const match = summaries.find(({ summary }) => (summary.video.markers ?? []).some((marker) => markers.has(marker.name)));
    if (!match) throw new Error(`Demo video for journey '${journey.id}' was not found in the run artifacts.`);
    const stepRecords = (await readFile(path.join(match.dir, 'files', 'browser', 'steps.jsonl'), 'utf8').catch(() => ''))
      .split('\n').filter(Boolean).map((line) => JSON.parse(line));
    const cuts = demoLoadCuts(stepRecords, journey.demo.video.loadKeepMs ?? 600, demoClickLeadMs(journey.demo.presentation));
    const sourceMs = match.summary.video.durationMs ?? 0;
    const trimmedMs = demoTrimmedTime(sourceMs, cuts);
    const maxSeconds = journey.demo.video.maxSeconds;
    if (maxSeconds && trimmedMs > maxSeconds * 1000) {
      throw new Error(`Demo video for journey '${journey.id}' runs ${(trimmedMs / 1000).toFixed(1)}s after trimming load time (recorded ${(sourceMs / 1000).toFixed(1)}s), over its ${maxSeconds}s limit (demo.video.maxSeconds).`);
    }
    const output = path.join(packageRoot, 'evidence', 'demo', `${journey.id}.mp4`);
    await mkdir(path.dirname(output), { recursive: true });
    const input = path.join(match.dir, match.summary.video.path);
    const encoded = spawnSync('ffmpeg', demoEncodeArgs(input, output, journey.demo, cuts), { stdio: 'inherit' });
    if (encoded.status !== 0) throw new Error(`ffmpeg failed encoding demo for ${journey.id}.`);
    if (journey.demo.cover) {
      const coverMarker = (match.summary.video.markers ?? []).find((marker) => marker.name === journey.demo.cover.marker);
      if (!coverMarker) throw new Error(`Cover marker '${journey.demo.cover.marker}' for journey '${journey.id}' is missing from the recorded video.`);
      const cover = path.join(path.dirname(output), `${journey.id}-cover.png`);
      const coverTime = demoTrimmedTime(coverMarker.endMs + 700, cuts);
      const coverArgs = ['-y', '-v', 'error', '-ss', String(coverTime / 1000), '-i', output, '-frames:v', '1'];
      const size = journey.demo.video.output;
      if (size) coverArgs.splice(coverArgs.length - 2, 0, '-vf', `scale=${size.width}:${size.height}:flags=lanczos`);
      coverArgs.push(cover);
      const extracted = spawnSync('ffmpeg', coverArgs, { stdio: 'inherit' });
      if (extracted.status !== 0) throw new Error(`ffmpeg failed extracting cover for ${journey.id}.`);
    }
    const stillScale = journey.demo.video.output ? ['-vf', `scale=${journey.demo.video.output.width}:${journey.demo.video.output.height}:flags=lanczos`] : [];
    for (const marker of match.summary.video.markers ?? []) {
      // The cover marker is written above as <id>-cover.png; never overwrite it.
      if (!marker.name || marker.name === journey.demo.cover?.marker) continue;
      const still = path.join(path.dirname(output), `${journey.id}-${marker.name}.png`);
      const stillTime = demoTrimmedTime(marker.endMs + 700, cuts);
      spawnSync('ffmpeg', ['-y', '-v', 'error', '-ss', String(stillTime / 1000), '-i', output, '-frames:v', '1', ...stillScale, still], { stdio: 'inherit' });
    }
  }
}

async function listFiles(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    return (await Promise.all(entries.map((entry) => entry.isDirectory() ? listFiles(path.join(directory, entry.name)) : [path.join(directory, entry.name)]))).flat();
  } catch { return []; }
}

export function runCodebox(args, capture = false) {
  const executable = process.env.HOMEBOY_WP_CODEBOX_BIN || process.env.WP_CODEBOX_BIN || 'wp-codebox';
  const maxBuffer = codeboxMaxBuffer();
  const env = { ...DEFAULT_DOWNLOAD_ENV, ...process.env };
  const result = spawnSync(executable, args, { encoding: 'utf8', stdio: capture ? 'pipe' : 'inherit', maxBuffer, env });
  if (result.error) {
    result.error.stdout = result.stdout || '';
    result.error.stderr = result.stderr || '';
    result.error.maxBuffer = maxBuffer;
    throw result.error;
  }
  if (capture && result.stderr) {
    process.stderr.write(result.stderr);
  }
  if (result.status !== 0) {
    // Surface Codebox's own diagnostics: CI discards this script's stdout, so a
    // failing `recipe validate` would otherwise report only an exit status.
    if (capture && result.stdout) {
      process.stderr.write(result.stdout);
    }
    const error = new Error(`WP Codebox exited with status ${result.status}.`);
    error.stdout = result.stdout || '';
    error.stderr = result.stderr || '';
    error.status = result.status;
    throw error;
  }
  return result;
}

function codeboxMaxBuffer() {
  const raw = process.env.HOMEBOY_WP_CODEBOX_MAX_BUFFER_BYTES;
  if (raw === undefined || raw === '') {
    return WP_CODEBOX_MAX_BUFFER_BYTES;
  }
  const value = Number(raw);
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error('HOMEBOY_WP_CODEBOX_MAX_BUFFER_BYTES must be a positive integer.');
  }
  return value;
}

function parseSettings(raw) {
  if (!raw) {
    return {};
  }
  const value = JSON.parse(raw);
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('HOMEBOY_SETTINGS_JSON must contain a JSON object.');
  }
  return value;
}

