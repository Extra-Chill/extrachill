// The EC_BLOG_ID_* constants (extrachill-network inc/core/blog-ids.php) carry
// production's blog IDs behind wp-config-style if(!defined()) guards. A fresh
// disposable install assigns new sequential blog IDs, so on an unaligned boot
// ec_is_events_site() and every cross-site route built on ec_get_blog_id()
// silently target the WRONG site (the docs site lands on blog 7 and inherits
// the events site's identity). This rig therefore projects its domain
// topology into those constants at runtime via a generated mu-plugin: each
// well-known domain is resolved against the actual sites table on every
// request, so the plugin set's expectations hold on any fresh install. This
// is rig infrastructure (domain resolution), not a product workaround; the
// upstream fix is for ec_get_blog_id() to resolve by domain itself.
const EC_DOMAIN_TO_BLOG_ID_CONSTANT = {
  'extrachill.com': 'EC_BLOG_ID_MAIN',
  'community.extrachill.com': 'EC_BLOG_ID_COMMUNITY',
  'shop.extrachill.com': 'EC_BLOG_ID_SHOP',
  'artist.extrachill.com': 'EC_BLOG_ID_ARTIST',
  'events.extrachill.com': 'EC_BLOG_ID_EVENTS',
  'newsletter.extrachill.com': 'EC_BLOG_ID_NEWSLETTER',
  'docs.extrachill.com': 'EC_BLOG_ID_DOCS',
  'wire.extrachill.com': 'EC_BLOG_ID_WIRE',
  'studio.extrachill.com': 'EC_BLOG_ID_STUDIO',
  'extrachill.link': 'EC_BLOG_ID_LINK_PAGES',
  'auth.extrachill.com': 'EC_BLOG_ID_AUTH',
};

export const DOMAIN_IDS_MU_PLUGIN_FILENAME = 'ec-network-domain-ids.php';

export function domainIdsMuPluginSource(topology) {
  const unknownDomains = Object.keys(EC_DOMAIN_TO_BLOG_ID_CONSTANT).filter(
    (domain) => !topology.sites.some((site) => site.domain === domain),
  );
  if (unknownDomains.length > 0) {
    throw new Error(`network-topology.json is missing rig domains with blog-ID constants: ${unknownDomains.join(', ')}`);
  }
  const entries = Object.entries(EC_DOMAIN_TO_BLOG_ID_CONSTANT)
    .map(([domain, constant]) => `\t\t'${domain}' => '${constant}',`)
    .join('\n');
  return `<?php
/**
 * GENERATED by rigs/extrachill-network/run.mjs from network-topology.json.
 * Do not edit: regenerate via the rig (homeboy rig install / up).
 *
 * Resolves the EC_BLOG_ID_* constants (extrachill-network inc/core/blog-ids.php)
 * from the actual sites table BY DOMAIN on every request. A fresh disposable
 * install assigns new sequential blog IDs, so the hardcoded production
 * defaults (events = 7, newsletter = 9, ...) would silently misroute every
 * ec_get_blog_id()/ec_is_events_site() consumer to the wrong site. The
 * if(!defined()) guards in blog-ids.php exist precisely so an earlier
 * definition wins; mu-plugins load before regular plugins.
 *
 * Skipped while WP_INSTALLING and on any request where the multisite API is
 * not loaded yet (the install-time blueprint request runs mu-plugins before
 * ms-blogs.php) -- the production defaults then apply harmlessly and later
 * requests resolve by domain.
 *
 * @package ExtraChillNetwork
 */

if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) || ! function_exists( 'get_sites' ) ) {
\treturn;
}

function ec_rig_network_resolve_domain_blog_ids() {
\tstatic $map = array(
${entries}
\t);
\tforeach ( $map as $domain => $constant ) {
\t\tif ( defined( $constant ) ) {
\t\t\tcontinue;
\t\t}
\t\t$sites = get_sites( array( 'domain' => $domain, 'number' => 1, 'fields' => 'all' ) );
\t\tif ( empty( $sites ) ) {
\t\t\tcontinue;
\t\t}
\t\tdefine( $constant, (int) $sites[0]->blog_id );
\t}
}
ec_rig_network_resolve_domain_blog_ids();
`;
}

export async function writeDomainIdsMuPlugin(directory, topology) {
  await mkdir(directory, { recursive: true });
  const target = path.join(directory, DOMAIN_IDS_MU_PLUGIN_FILENAME);
  await writeFile(target, domainIdsMuPluginSource(topology));
  return target;
}

export const SANDBOX_COMPAT_MU_PLUGIN_FILENAME = 'ec-network-sandbox-compat.php';

/**
 * Sandbox compatibility mu-plugin (extrachill-network#302, #299): the
 * disposable-runtime gaps every browser journey hits. Each substitutes a
 * missing piece of infrastructure, never product behaviour, and exists only
 * inside the disposable boot.
 */
export function sandboxCompatMuPluginSource() {
  return `<?php
/**
 * GENERATED by rigs/extrachill-network/run.mjs (extrachill-network#302).
 * Disposable-sandbox compatibility only; never deployed.
 */

/*
 * 1. http vs https. The sandbox serves plain http, but ec_get_site_url() and
 *    the Link Pages public base URL build https:// URLs, so cross-site hops
 *    (/join, bridge cards, editor handoff, canonical redirects) dead-end on a
 *    TLS port nothing answers. Answer with each site's real home URL through
 *    the override extrachill-network ships for dev environments, and
 *    downgrade redirects to network hosts.
 */
add_filter(
\t'ec_site_url_override',
\tstatic function ( $url, $key, $blog_id ) {
\t\tunset( $key );
\t\treturn $blog_id ? untrailingslashit( get_home_url( (int) $blog_id ) ) : $url;
\t},
\t10,
\t3
);
add_filter(
\t'wp_redirect',
\tstatic function ( $location ) {
\t\treturn is_string( $location ) ? preg_replace( '#^https://((?:[a-z0-9-]+\\\\.)?extrachill\\\\.(?:com|link))(?=[/?\\\\#]|$)#i', 'http://$1', $location ) : $location;
\t},
\tPHP_INT_MAX - 1
);

/*
 * 1b. Same downgrade for URLs the product emits directly rather than via a
 *     redirect: escaped links in HTML (clean_url) and URLs inside REST
 *     responses (e.g. the Link Page owner pencil's manage_url). Production
 *     is https end to end.
 */
function ec_rig_downgrade_network_urls( $value ) {
	if ( is_string( $value ) ) {
		return preg_replace( '#https://((?:[a-z0-9-]+\\.)?extrachill\\.(?:com|link))(?=[/?\\#"]|$)#i', 'http://$1', $value );
	}
	if ( is_array( $value ) ) {
		return array_map( 'ec_rig_downgrade_network_urls', $value );
	}
	return $value;
}
add_filter( 'clean_url', 'ec_rig_downgrade_network_urls', PHP_INT_MAX );
add_filter(
	'rest_post_dispatch',
	static function ( $response ) {
		if ( $response instanceof WP_REST_Response ) {
			$response->set_data( ec_rig_downgrade_network_urls( $response->get_data() ) );
		}
		return $response;
	},
	PHP_INT_MAX
);

/*
 * 3. No persistent object cache. Redis is an excluded component on this rig,
 *    and the network's two atomic abuse limiters fail closed without one:
 *    Extra Chill Users registration (registration_limiter_unavailable, 503;
 *    every browser sign-up) and extrachill-api public writes (register,
 *    login, refresh). Both expose a store seam; answer them with a
 *    site-option counter. Requests are serialized, so this is not a claim
 *    of atomicity under real concurrency (extrachill-network#299).
 */
function ec_rig_sandbox_counter( $key, $ttl ) {
	$state = get_site_option( 'ec_rig_sandbox_counters', array() );
	$now   = time();
	$entry = $state[ $key ] ?? array( 'count' => 0, 'expires' => $now + max( 1, (int) $ttl ) );
	if ( $entry['expires'] <= $now ) {
		$entry = array( 'count' => 0, 'expires' => $now + max( 1, (int) $ttl ) );
	}
	++$entry['count'];
	$state[ $key ] = $entry;
	update_site_option( 'ec_rig_sandbox_counters', $state );
	return (int) $entry['count'];
}
add_filter(
	'extrachill_api_rate_limit_store',
	static function () {
		return 'ec_rig_sandbox_counter';
	}
);
add_filter(
	'extrachill_users_registration_admitter',
	static function ( $admitter ) {
		if ( ! function_exists( 'extrachill_users_registration_attempt_key' ) || ! defined( 'EXTRACHILL_USERS_REGISTRATION_RATE_WINDOW' ) || ! defined( 'EXTRACHILL_USERS_REGISTRATION_RATE_LIMIT' ) ) {
			return $admitter;
		}
		return static function () {
			$key = extrachill_users_registration_attempt_key();
			if ( '' === $key ) {
				return new WP_Error( 'registration_limiter_unavailable', 'Registration is temporarily unavailable.', array( 'status' => 503 ) );
			}
			$window     = EXTRACHILL_USERS_REGISTRATION_RATE_WINDOW;
			$expires_at = ( intdiv( time(), $window ) + 1 ) * $window;
			$count      = ec_rig_sandbox_counter( 'registration_' . $key, 2 * $window );
			return $count > EXTRACHILL_USERS_REGISTRATION_RATE_LIMIT && function_exists( 'extrachill_users_registration_rate_limit_error' )
				? extrachill_users_registration_rate_limit_error( $expires_at )
				: true;
		};
	}
);

/*
 * 4. SQLite has no MySQL advisory locks, so every GET_LOCK()-serialized write
 *    (Link Page creation and saves, artist membership) fails closed. Requests
 *    are serialized through one PHP runtime here, so answer as MySQL would.
 *    Not a claim of concurrency safety.
 */
add_filter(
\t'query',
\tstatic function ( $query ) {
\t\tif ( is_string( $query ) && preg_match( '/^\\\\s*SELECT\\\\s+(GET_LOCK|RELEASE_LOCK|IS_FREE_LOCK)\\\\s*\\\\(/i', $query ) ) {
\t\t\treturn 'SELECT 1';
\t\t}
\t\treturn $query;
\t}
);
`;
}

