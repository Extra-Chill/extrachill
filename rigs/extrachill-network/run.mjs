export function paceDemoSteps(raw, pacing = {}) {
  if (!pacing.settleMs && !pacing.minCaptionMs) return raw;
  const steps = typeof raw === 'string' ? JSON.parse(raw) : raw;
  const paced = [];
  for (const step of steps) {
    paced.push(step);
    if ((step.kind === 'navigate' || step.kind === 'click') && pacing.settleMs > 0) {
      paced.push({ kind: 'waitFor', waitFor: 'duration', duration: `${pacing.settleMs}ms` });
    }
    // A caption with its own durationMs is followed by an authored wait; only
    // untimed captions need the minimum on-screen time inserted.
    if (step.kind === 'annotate' && step.shape === 'caption' && pacing.minCaptionMs > 0 && step.durationMs === undefined) {
      paced.push({ kind: 'waitFor', waitFor: 'duration', duration: `${pacing.minCaptionMs}ms` });
    }
  }
  return JSON.stringify(paced);
}

/**
 * Video ranges to cut from a demo recording: the dead time while a page loads.
 *
 * Rig page loads take seconds (a cold sandbox can take tens of seconds on one
 * click), which the viewer should never sit through. Every step that waits on
 * a navigation -- `navigate`, `waitFor` load states, and the `click` that
 * triggers one -- keeps at most `keepMs` of its footage (the start, so the tap
 * and the first paint stay visible) and the rest is cut. Authored pacing
 * (duration waits) and every other step are never trimmed.
 *
 * @param {Array<object>} steps  steps.jsonl records with videoOffsetMs.
 * @param {number} keepMs        Footage kept per load step.
 * @returns {Array<[number, number]>} Sorted, merged [startMs, endMs) cuts.
 */
// A presented click spends its opening moments gliding the cursor to the
// target and playing click feedback; the navigation only starts after that.
export const DEMO_CLICK_FEEDBACK_MS = 250;
export function demoClickLeadMs(presentation) {
  const move = Number(presentation?.motion?.moveDurationMs ?? 0);
  const feedback = presentation?.clickFeedback === false || presentation?.clickFeedback?.enabled === false ? 0 : DEMO_CLICK_FEEDBACK_MS;
  return Math.max(0, (Number.isFinite(move) ? move : 0) + feedback);
}

export function demoLoadCuts(steps, keepMs = 600, clickLeadMs = 0) {
  const loadStates = new Set(['load', 'domcontentloaded', 'networkidle']);
  const cuts = [];
  const waitsOnLoad = (step) => step?.kind === 'waitFor' && loadStates.has(step.waitFor);
  for (const [index, step] of steps.entries()) {
    const offset = step.videoOffsetMs;
    if (!offset || !(offset.endMs > offset.startMs)) continue;
    // A click followed by a load wait triggered a navigation. Demo pacing may
    // insert one settle wait between them, so look one step further.
    const isDurationWait = (candidate) => candidate?.kind === 'waitFor' && candidate.waitFor === 'duration';
    const navigatingClick = step.kind === 'click' && (waitsOnLoad(steps[index + 1]) || (isDurationWait(steps[index + 1]) && waitsOnLoad(steps[index + 2])));
    const isLoad = step.kind === 'navigate' || waitsOnLoad(step) || navigatingClick;
    if (!isLoad) continue;
    // A load wait right after another load step continues the same page
    // transition, whose kept footage was already taken: cut all of it.
    const previous = steps[index - 1];
    const beforePrevious = steps[index - 2];
    const continuesTransition = waitsOnLoad(step) && (['click', 'navigate'].includes(previous?.kind) || waitsOnLoad(previous) || (isDurationWait(previous) && ['click', 'navigate'].includes(beforePrevious?.kind)));
    // Keep a navigating click's cursor glide and feedback, then keepMs of the transition.
    const start = continuesTransition ? offset.startMs : offset.startMs + (navigatingClick ? clickLeadMs : 0) + keepMs;
    if (offset.endMs - start > 50) cuts.push([start, offset.endMs]);
  }
  // Blank frames before the first step (context start, first request) never show.
  const firstStart = steps.find((step) => step.videoOffsetMs)?.videoOffsetMs.startMs ?? 0;
  if (firstStart > 50) cuts.push([0, firstStart]);
  const firstLoad = steps.find((step) => {
    const offset = step.videoOffsetMs;
    return offset && offset.endMs > offset.startMs && (step.kind === 'navigate' || waitsOnLoad(step));
  });
  if (firstLoad) {
    const end = firstLoad.videoOffsetMs.endMs + keepMs;
    if (end > 50) cuts.push([0, end]);
  }
  cuts.sort((a, b) => a[0] - b[0]);
  const merged = [];
  for (const cut of cuts) {
    const last = merged[merged.length - 1];
    if (last && cut[0] <= last[1]) last[1] = Math.max(last[1], cut[1]);
    else merged.push([...cut]);
  }
  return merged;
}

/** Map a source-video time to the trimmed timeline. */
export function demoTrimmedTime(ms, cuts) {
  let removed = 0;
  for (const [start, end] of cuts) {
    if (ms >= end) removed += end - start;
    else if (ms > start) return start - removed;
  }
  return ms - removed;
}

export function demoEncodeArgs(input, output, demo, cuts = []) {
  const out = demo.video.output;
  const keep = cuts.length
    ? [`select='not(${cuts.map(([a, b]) => `between(t,${(a / 1000).toFixed(3)},${(b / 1000).toFixed(3)})`).join('+')})'`, 'setpts=N/FRAME_RATE/TB']
    : [];
  const filters = [
    ...keep,
    ...(out ? [`scale=${out.width}:${out.height}:flags=lanczos`] : []),
    ...(out?.fps ? [`fps=${out.fps}`] : []),
    'format=yuv420p',
  ];
  return ['-y', '-v', 'error', '-i', input, '-vf', filters.join(','), '-c:v', 'libx264', '-preset', 'slow', '-crf', '18', '-movflags', '+faststart', '-an', output];
}

export function journeyMarkers(journey) {
  const markers = [];
  for (const step of journey.steps) {
    const raw = (step.args ?? []).find((arg) => arg.startsWith('steps-json='));
    if (!raw) continue;
    try {
      for (const action of JSON.parse(raw.slice('steps-json='.length))) if (action.marker) markers.push(action.marker);
    } catch { /* validated elsewhere */ }
  }
  return markers;
}

function assertJourneyStepScoping(id, journey) {
  journey.steps.forEach((step, index) => {
    const args = step.args ?? [];
    const urls = args.filter((arg) => arg.startsWith('url=')).map((arg) => arg.slice('url='.length));
    const allowed = new Set(journey.sites);
    for (const rawUrl of urls) {
      let host;
      try {
        host = new URL(rawUrl).host;
      } catch {
        throw new Error(`Journey '${id}' step ${index} has a non-absolute url '${rawUrl}'. Journey steps use absolute http://<domain>/ URLs so every step targets a declared site by domain.`);
      }
      if (!allowed.has(host)) {
        throw new Error(`Journey '${id}' step ${index} targets '${host}', which is outside the journey's declared sites (${[...allowed].join(', ')}).`);
      }
    }
    for (const argKey of ['route-host', 'allow-host']) {
      // Both args are wp-codebox "repeatable" hostnames (route-host also
      // accepts one comma-separated value): a journey step driving a real
      // cross-site flow (e.g. a browser-handoff redirect) legitimately
      // declares more than one. Every declared host -- not just the first
      // occurrence -- must stay inside the journey's declared sites.
      const hosts = args
        .filter((arg) => arg.startsWith(`${argKey}=`))
        .flatMap((arg) => arg.slice(argKey.length + 1).split(','))
        .map((host) => host.trim())
        .filter((host) => host !== '');
      for (const host of hosts) {
        if (!allowed.has(host)) {
          throw new Error(`Journey '${id}' step ${index} sets ${argKey} to '${host}', outside the journey's declared sites.`);
        }
      }
    }
    if (step.metadata?.kind !== undefined && step.metadata.kind !== 'journey-browser-step') {
      throw new Error(`Journey '${id}' step ${index} uses reserved metadata kind '${step.metadata.kind}'.`);
    }
  });
}

function journeyStep(journey, dir, step) {
  const substitute = (value) => (typeof value === 'string' ? value.replaceAll('${journey.dir}', dir).replaceAll('${journey.id}', journey.id) : value);
  // Emit only keys the WP Codebox recipe schema accepts: it rejects unknown
  // step properties, so journey-only annotations (e.g. a step `marker`) must
  // never leak into the recipe.
  const { command, args, metadata, timeoutMs, env } = step;
  return {
    command,
    ...(timeoutMs !== undefined ? { timeoutMs } : {}),
    ...(env !== undefined ? { env } : {}),
    // See journeyPhaseStep: every journey step is isolated from the others.
    allowFailure: true,
    args: (args ?? []).map(substitute),
    metadata: { ...(metadata ?? {}), kind: metadata?.kind ?? 'journey-browser-step', journey: journey.id },
  };
}

function journeyPhaseStep(journey, dir, phase) {
  const phaseConfig = journey[phase];
  if (!phaseConfig?.codeFile) {
    return undefined;
  }
  return {
    command: 'wordpress.run-php',
    args: [`code-file=${path.join(dir, phaseConfig.codeFile)}`],
    ...(phaseConfig.timeoutMs ? { timeoutMs: phaseConfig.timeoutMs } : {}),
    // Journey isolation: one journey's fatal must not stop the recipe and
    // discard every other selected journey's results. The failure is still
    // recorded (stepFailures) and the journeys workflow fails on it.
    allowFailure: true,
    metadata: { kind: `journey-${phase}`, journey: journey.id },
  };
}

/**
 * wp-codebox's wordpress.run-php always bootstraps every request with the
 * SAME simulated identity -- HTTP_HOST/REQUEST_URI copied from wp-config.php's
 * DOMAIN_CURRENT_SITE/PATH_CURRENT_SITE (see
 * @automattic/wp-codebox-playground's multisiteRequestBootstrapPhp()), i.e.
 * every single run-php call looks identical to an anonymous GET of the
 * primary site's homepage. extrachill-cache's advanced-cache.php drop-in
 * (correctly, for a real front-end request) serves a stored page for that
 * exact identity and exits before WordPress finishes loading -- BEFORE our
 * injected eval code ever runs -- the moment any earlier step (a baseline
 * browser-probe, a journey browser-action) has actually visited that
 * homepage as a real anonymous visitor and warmed the cache. That produces a
 * run-php step wp-codebox itself reports as "succeeded" while our PHP never
 * executed at all: this rig hit it for real (the journey's seed AND grade
 * run-php steps both silently returned cached homepage HTML, evidenced by an
 * identical "Cached by Extra Chill Cache" timestamp on both). Filed upstream
 * at Automattic/wp-codebox with a minimal repro; wp-cli's own bootstrap
 * (wp-cli-command-handlers.js) never sets $_SERVER['REQUEST_METHOD'], so
 * advanced-cache.php's "only GET requests can hit the anonymous cache" gate
 * returns immediately and lets WordPress load for real -- purging through
 * wordpress.wp-cli, not wordpress.run-php, is what actually reaches the
 * plugin's own `wp extrachill-cache purge --all` command.
 */
function cachePurgeStep(journeyId, phase) {
  return {
    command: 'wordpress.wp-cli',
    args: ['command=extrachill-cache purge --all'],
    allowFailure: true,
    metadata: { kind: `journey-${phase}-cache-purge`, journey: journeyId },
  };
}

export async function buildJourneys(settings, topology) {
  const ids = journeySelection(settings);
  const known = await availableJourneys();
  for (const id of ids) {
    if (!known.includes(id)) {
      throw new Error(`Unknown extrachill_journeys entry '${id}'. Available journeys: ${known.join(', ') || '(none)'}.`);
    }
  }
  const loaded = [];
  for (const id of ids) {
    loaded.push(await loadJourney(id, topology));
  }
  return loaded;
}

export async function buildRecipe(settings = {}, cwd = process.cwd()) {
  const topology = await loadJson('network-topology.json');
  const components = await loadJson('components.json');

  const overrides = isRecord(settings.extrachill_component_source_overrides) ? settings.extrachill_component_source_overrides : {};
  const releaseSet = isRecord(settings.extrachill_release_set) ? settings.extrachill_release_set : {};
  const includeExcluded = new Set(Array.isArray(settings.extrachill_include_excluded_components) ? settings.extrachill_include_excluded_components : []);

  const activePlugins = [...components.plugins];
  for (const excluded of components.excludedComponents) {
    if (includeExcluded.has(excluded.slug) && overrides[excluded.slug]) {
      activePlugins.push({ slug: excluded.slug, source: 'override-only', activations: excluded.forcedActivations ?? [] });
    }
  }

  const monorepoSources = await prepareMonorepoSources(settings, activePlugins, components.theme, artifactsRoot(cwd));
  const pinnedReleaseSet = await pinMonorepoReleases(activePlugins, overrides, releaseSet, monorepoSources);
  const extraPlugins = activePlugins.map((component) => ({
    source: resolveComponentSource(component, overrides, pinnedReleaseSet, monorepoSources),
    slug: component.slug,
    // wp-codebox validates a single pluginFile exists in the mounted source
    // regardless of activate:false; components whose main file does not
    // follow the <slug>/<slug>.php convention (e.g. the wp.org AI provider
    // plugins ship plugin.php) need it set explicitly. The rig itself
    // activates every declared activation below, not just this one.
    ...(component.activations?.[0]?.pluginFile ? { pluginFile: component.activations[0].pluginFile } : {}),
    activate: false,
    loadAs: 'plugin',
    metadata: { extrachillActivations: component.activations },
  }));

  const themeSource = overrides[components.theme.slug] || monorepoSources[components.theme.slug] || settings.extrachill_theme_source;
  const theme = buildThemeInputs(components.theme, themeSource);

  const additionalPrepareSteps = recipeArray(settings.wordpress_runtime_prepare_steps, 'wordpress_runtime_prepare_steps');
  const additionalPostSteps = recipeArray(settings.wordpress_runtime_post_steps, 'wordpress_runtime_post_steps');
  const phpVersion = runtimePhpVersion(settings);

  const journeys = await buildJourneys(settings, topology);
  const demoMode = settings.extrachill_demo === true;
  const demoThemes = new Map();
  if (demoMode) {
    for (const { journey } of journeys) {
      if (!journey.demo) throw new Error(`Journey '${journey.id}' has no demo contract.`);
      if (!demoThemes.has(journey.demo.theme)) {
        demoThemes.set(journey.demo.theme, JSON.parse(await readFile(path.join(packageRoot, 'demo-themes', journey.demo.theme), 'utf8')));
      }
    }
  }

  const activationHookExceptions = (components.activationHookExceptions ?? []).map((entry) => entry.pluginFile);
  const activationMatrix = buildActivationMatrix(topology, activePlugins, components.excludedComponents, activationHookExceptions);

  const muPluginPath = await writeDomainIdsMuPlugin(artifactsRoot(cwd), topology);
  const sandboxCompatPath = await writeSandboxCompatMuPlugin(artifactsRoot(cwd));

  const runtimeEnv = {};
  for (const { journey } of journeys) {
    Object.assign(runtimeEnv, journey.runtimeEnv ?? {});
  }

  const cacheActive = activePlugins.some((component) => component.slug === 'extrachill-cache');

  // Journey fixture mu-plugins (extrachill-network/journey/v1's optional
  // "fixtureMuPlugins"): journey-owned PHP files that must run on EVERY
  // request for the lifetime of the boot, not just inside one run-php
  // step's own process (e.g. a persistent add_filter() a browser-driven
  // registration/delivery flow needs live while it makes its own separate
  // HTTP requests). Generic rig mounting; the vendor-specific content (a
  // Turnstile bypass filter, a provider HTTP stub, ...) lives entirely
  // inside the journey's own file, never in this rig.
  const journeyFixtureMuPluginMounts = [];
  for (const { journey, dir } of journeys) {
    for (const file of journey.fixtureMuPlugins ?? []) {
      journeyFixtureMuPluginMounts.push({
        type: 'file',
        source: path.join(dir, file),
        target: `/wordpress/wp-content/mu-plugins/journey-${journey.id}-${path.basename(file)}`,
        mode: 'readonly',
        metadata: { kind: 'journey-fixture-mu-plugin', journey: journey.id, file },
      });
    }
  }

  // extrachill_journey_seed: one optional, generic deterministic seed string
  // any journey's own seed.php may read (get_site_option('ec_rig_journey_seed', ...))
  // to build a replayable, seeded case plan (e.g. a fuzz campaign's generated
  // email/device IDs). The rig only carries the opaque string through; it
  // has no idea what a journey does with it.
  const journeySeed = journeySeedSetting(settings);

  const journeySteps = [];
  if (journeys.length > 0 && journeySeed !== undefined) {
    journeySteps.push(journeySeedStep(journeySeed));
  }
  for (const { journey, dir } of journeys) {
    const seed = journeyPhaseStep(journey, dir, 'seed');
    if (seed) {
      if (cacheActive) {
        journeySteps.push(cachePurgeStep(journey.id, 'seed'));
      }
      journeySteps.push(seed);
    }
    journeySteps.push(...journey.steps.map((step) => {
      const prepared = journeyStep(journey, dir, step);
      if (demoMode && step.command === 'wordpress.browser-actions') {
        prepared.args = [...prepared.args.filter((arg) => !arg.startsWith('capture=')), ...assembleDemoArgs(journey.demo, demoThemes.get(journey.demo.theme))];
        if (journey.demo.pacing) {
          prepared.args = prepared.args.map((arg) => arg.startsWith('steps-json=') ? `steps-json=${paceDemoSteps(arg.slice('steps-json='.length), journey.demo.pacing)}` : arg);
        }
      }
      return prepared;
    }));
    const grade = journeyPhaseStep(journey, dir, 'grade');
    if (grade) {
      if (cacheActive) {
        journeySteps.push(cachePurgeStep(journey.id, 'grade'));
      }
      journeySteps.push(grade);
    }
  }

  const workflowSteps = [
    activatePluginsStep(activationMatrix),
    ...(theme.activateStep ? [theme.activateStep] : []),
    activationAssertionStep(topology, activationMatrix, components.excludedComponents, includeExcluded),
    ...additionalPrepareSteps,
    ...topology.sites.map((site) => browserProbeStep(site)),
    ...journeySteps,
    ...additionalPostSteps,
  ];

  return {
    schema: 'wp-codebox/workspace-recipe/v1',
    runtime: {
      backend: 'wordpress',
      ...(settings.wordpress_runtime_version ? { wp: settings.wordpress_runtime_version } : {}),
      ...(phpVersion ? { phpVersion } : {}),
      blueprint: { steps: [] },
      preview: { siteUrl: `http://${topology.sites.find((site) => site.primary)?.domain ?? topology.sites[0].domain}/` },
    },
    inputs: {
      ...(Object.keys(runtimeEnv).length > 0 ? { runtimeEnv } : {}),
      extra_plugins: extraPlugins,
      ...(theme.extraThemes ? { extra_themes: theme.extraThemes } : {}),
      mounts: [
        {
          type: 'file',
          source: muPluginPath,
          target: `/wordpress/wp-content/mu-plugins/${DOMAIN_IDS_MU_PLUGIN_FILENAME}`,
          mode: 'readonly',
          metadata: { kind: 'extrachill-network-domain-ids', generated: true, note: 'Resolves EC_BLOG_ID_* constants from the actual sites table by domain; see run.mjs EC_DOMAIN_TO_BLOG_ID_CONSTANT.' },
        },
        {
          type: 'file',
          source: sandboxCompatPath,
          target: `/wordpress/wp-content/mu-plugins/${SANDBOX_COMPAT_MU_PLUGIN_FILENAME}`,
          mode: 'readonly',
          metadata: { kind: 'extrachill-network-sandbox-compat', generated: true, note: 'http/https URL resolution, Redis-less rate-limiter stores, SQLite advisory-lock answers; see run.mjs sandboxCompatMuPluginSource.' },
        },
        ...(theme.mounts ? theme.mounts : []),
        ...journeyFixtureMuPluginMounts,
      ],
      siteSeeds: [{
        type: 'parent_site',
        name: 'extrachill-network-topology',
        // parent_site export is not implemented upstream yet (recipe-site-seeds.ts
        // reports this seed as "skipped"), so no data actually crosses from
        // production; this scope only exists to satisfy schema validation's
        // bounded-scope requirement for a parent_site declaration.
        scopes: { options: { names: ['blogname'], maxRecords: 1 } },
        bootstrap: {
          multisite: {
            enabled: true,
            install: topology.install,
            sites: topology.sites.map((site) => ({ domain: site.domain, path: site.path, title: site.title })),
          },
          domains: topology.sites.map((site) => ({ domain: site.domain, path: site.path, primary: Boolean(site.primary) })),
        },
      }],
    },
    workflow: { steps: workflowSteps },
    artifacts: {
      directory: artifactsRoot(cwd),
    },
    ...(journeys.length > 0
      ? {
          metadata: {
            extrachillJourneys: journeys.map(({ journey }) => ({
              id: journey.id,
              persona: journey.persona?.id ?? null,
              sites: journey.sites,
            })),
          },
        }
      : {}),
  };
}

